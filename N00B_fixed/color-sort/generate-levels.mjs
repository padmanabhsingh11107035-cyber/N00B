// Makes the levels of Color Sort: random full bottles, kept only when the solver can win them. Writes instagram/public/games/color-sort/levels.js.
//   node generate-levels.mjs            (a few minutes at most; the result does not change between runs: the random numbers are seeded)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { solve, replay, rules as R } from './solver.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(here, '../instagram/public/games/color-sort/levels.js');

function rng(seed) {   // mulberry32
  let a = seed >>> 0;
  return () => { a = (a + 0x6D2B79F5) >>> 0; let t = a; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
}

// [bottles, colours, empty bottles]: the first levels are small and get bigger; the last ones are the full board of 24 bottles. With six colours there is a spare empty bottle.
const PLAN = [
  [6, 3], [8, 3], [8, 4], [10, 4], [12, 4], [12, 5], [14, 5], [16, 5], [18, 5], [20, 5], [22, 5], [24, 5],
  [16, 5], [18, 6, 1], [20, 5], [24, 5], [20, 6, 1], [23, 6, 1], [18, 5], [24, 5],
  [22, 6, 1], [24, 5], [20, 5], [23, 6, 1], [16, 6, 1], [24, 5], [23, 6, 1], [18, 6, 1], [24, 5], [23, 6, 1],
];

function makeBoard(bottles, colours, rand, empties = 0) {
  const units = [];
  const total = bottles * R.BOTTLE_CAP;
  for (let i = 0; i < total; i++) units.push(i % colours);
  for (let i = units.length - 1; i > 0; i--) { const j = Math.floor(rand() * (i + 1)); [units[i], units[j]] = [units[j], units[i]]; }
  const level = [];
  for (let b = 0; b < bottles; b++) level.push(units.slice(b * R.BOTTLE_CAP, (b + 1) * R.BOTTLE_CAP).join(''));
  for (let e = 0; e < empties; e++) level.push('');
  return level;
}

const levels = [];
const stats = [];
PLAN.forEach(([bottles, colours, empties = 0], n) => {
  const rand = rng(1000 + n * 7919);
  for (let attempt = 1; ; attempt++) {
    const level = makeBoard(bottles, colours, rand, empties);
    const mono = level.filter((b) => b && new Set(b).size === 1).length;
    if (mono > bottles / 6) continue;             // not a pile of ready-made bottles
    const state = R.fromLevel(level);
    const moves = solve(state, 15000, 3000);
    if (!moves || !replay(state, moves)) continue;
    levels.push(level);
    stats.push({ n: n + 1, bottles, colours, attempt, moves: moves.length });
    console.log('level', n + 1, bottles, colours, 'tries', attempt, 'pours', moves.length);
    break;
  }
});

const text = '// Generated by color-sort/generate-levels.mjs (instagram/public/games/color-sort/levels.js): every level was won by the solver before it was kept.\n'
  + '// A level is a list of bottles, bottom to top ("0312": colours 0, 3, 1, 2); the big tube always starts empty.\n'
  + 'window.COLOR_SORT_LEVELS=[\n' + levels.map((l) => ' ' + JSON.stringify(l)).join(',\n') + '\n];\n';
fs.writeFileSync(OUT, text);
console.log(stats.map((s) => `L${s.n}: ${s.bottles} bottles, ${s.colours} colours, found after ${s.attempt} tries, solved in ${s.moves} pours`).join('\n'));
console.log('written', OUT, text.length, 'bytes');
