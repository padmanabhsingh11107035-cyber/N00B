// Makes the levels of Color Sort: every colour 4 units shuffled into full bottles, kept only when the solver can win them. Writes instagram/public/games/color-sort/levels.js.
//   node generate-levels.mjs            (a few minutes at most; the result does not change between runs: the random numbers are seeded)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { solve, replay, rules as R } from './solver.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(here, '../instagram/public/games/color-sort/levels.js');

function rng(seed) {   // mulberry32
  let a = seed >>> 0;
  return () => { a = (a + 0x6D2B79F5) >>> 0; let t = a; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
}

// [colours, empty bottles]: every colour is exactly 4 units, so a level has one full bottle per colour (mixed up) plus the empty ones. The first levels are small and grow;
// with only one empty bottle a level is much harder, so those come later.
const PLAN = [
  [3, 2], [4, 2], [5, 2], [5, 2], [6, 2], [6, 2], [7, 2], [7, 2], [8, 2], [8, 2],
  [9, 2], [9, 2], [10, 2], [10, 2], [11, 2], [11, 2], [12, 2], [12, 2], [13, 2], [13, 2],
  [14, 2], [14, 2], [5, 1], [6, 1], [7, 1], [8, 1], [9, 1], [10, 1], [11, 1], [12, 1],
  [13, 2], [14, 2], [8, 1], [9, 1], [10, 1], [11, 1], [12, 1], [13, 1], [14, 2], [14, 2],
];

function makeBoard(colours, empties, rand) {
  const units = [];
  for (let c = 0; c < colours; c++) for (let k = 0; k < R.BOTTLE_CAP; k++) units.push(c);
  for (let i = units.length - 1; i > 0; i--) { const j = Math.floor(rand() * (i + 1)); [units[i], units[j]] = [units[j], units[i]]; }
  const level = [];
  for (let b = 0; b < colours; b++) level.push(units.slice(b * R.BOTTLE_CAP, (b + 1) * R.BOTTLE_CAP).map((c) => String.fromCharCode(48 + c)).join(''));
  for (let e = 0; e < empties; e++) level.push('');
  return level;
}

const levels = [];
const stats = [];
PLAN.forEach(([colours, empties], n) => {
  const rand = rng(1000 + n * 7919);
  for (let attempt = 1; ; attempt++) {
    const level = makeBoard(colours, empties, rand);
    if (level.some((b) => b && R.isCapped(R.fromLevel([b])[0]))) continue;   // no bottle is finished before the first pour
    const state = R.fromLevel(level);
    const moves = solve(state, 40000, 6000);
    if (!moves || !replay(state, moves)) continue;
    levels.push(level);
    stats.push({ n: n + 1, colours, empties, attempt, moves: moves.length });
    console.log('level', n + 1, colours + ' colours +' + empties, 'tries', attempt, 'pours', moves.length);
    break;
  }
});

const text = '// Generated by color-sort/generate-levels.mjs (instagram/public/games/color-sort/levels.js): every level was won by the solver before it was kept.\n'
  + '// A level is a list of bottles, bottom to top ("0312": colours 0, 3, 1, 2); the big tube always starts empty.\n'
  + 'window.COLOR_SORT_LEVELS=[\n' + levels.map((l) => ' ' + JSON.stringify(l)).join(',\n') + '\n];\n';
fs.writeFileSync(OUT, text);
console.log(stats.map((s) => `L${s.n}: ${s.colours} colours + ${s.empties} empty, found after ${s.attempt} tries, solved in ${s.moves} pours`).join('\n'));
console.log('written', OUT, text.length, 'bytes');
