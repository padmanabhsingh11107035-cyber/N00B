// Makes src/data/worldMapPath.ts: the land outlines and country borders of the world as two compact SVG path strings (Natural Earth 110m, public domain, from the npm package world-atlas).
// Run once, by hand, from a scratch folder that holds the three helper packages (they are NOT dependencies of the app):
//   mkdir <scratch> && cd <scratch> && npm init -y && npm i world-atlas@2 topojson-client d3-geo
//   node scripts/gen-world-map.mjs <scratch>
// Projection: plain equirectangular, 1000 units = 360 degrees, latitudes 84 N .. 58 S (no Antarctica). x = (lon+180)*1000/360, y = (84-lat)*1000/360. src/utils/geoPlaces.ts uses the same formula.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const scratch = path.resolve(process.argv[2] || '.');
const req = createRequire(path.join(scratch, 'noop.js'));
const topo = req('topojson-client');
const d3 = req('d3-geo');
const land110 = JSON.parse(fs.readFileSync(path.join(scratch, 'node_modules/world-atlas/land-110m.json'), 'utf8'));
const ctr110 = JSON.parse(fs.readFileSync(path.join(scratch, 'node_modules/world-atlas/countries-110m.json'), 'utf8'));

const W = 1000, TOP = 84, BOTTOM = -58, H = Math.round(((TOP - BOTTOM) * W) / 360 * 10) / 10;
const k = W / (2 * Math.PI);
const projection = d3.geoEquirectangular().scale(k).translate([W / 2, (TOP * Math.PI / 180) * k]).clipExtent([[0, 0], [W, H]]).precision(0.5);
const gp = d3.geoPath(projection).digits(1);

const land = gp(topo.feature(land110, land110.objects.land));
const borders = gp(topo.mesh(ctr110, ctr110.objects.countries, (a, b) => a !== b));
const out = `// Generated by scripts/gen-world-map.mjs from Natural Earth 110m (public domain, npm package world-atlas). Do not edit by hand.
// Equirectangular, ${W} units = 360 degrees, latitude ${TOP} N (top) to ${-BOTTOM} S (bottom). x = (lon + 180) * ${W} / 360, y = (${TOP} - lat) * ${W} / 360.
export const WORLD_MAP_WIDTH = ${W};
export const WORLD_MAP_HEIGHT = ${H};
export const WORLD_LAND_PATH = ${JSON.stringify(land)};
export const WORLD_BORDERS_PATH = ${JSON.stringify(borders)};
`;
fs.mkdirSync('src/data', { recursive: true });
fs.writeFileSync('src/data/worldMapPath.ts', out);
console.log(`land ${land.length} bytes, borders ${borders.length} bytes, file ${out.length} bytes, height ${H}`);
