// Writes supabase/one-off/gap-b-live-check.sql: the READ-ONLY catalog check the owner runs in the Supabase SQL editor (Stage 4 of docs/PRIVACY-GAP-B-PLAN.md).
// The expected fingerprints (md5 of every function's source) are computed here from the repository's own migrations on a throwaway in-memory Postgres (PGlite):
//   "before" = every migration up to 20261114000019, "after" = plus the five gap-B migrations 20261114000020 to 20261114000024.
// Run again (node --liftoff-only scripts/supabase/make-gap-b-live-check.mjs) whenever one of those functions changes in a later migration. Nothing here touches a real database.
import fs from 'node:fs';
import path from 'node:path';
import { createTestDb, MIGRATIONS_DIR } from './pg-test-env.mjs';

const WATCH = ['search_users', 'user_by_id', 'mutual_followers', 'post_likers', 'reel_likers', 'user_public_json', 'post_json', 'reel_json', 'story_json', 'music_json', 'long_video_json', 'message_json', 'chat_json',
  'comment_json', 'team_application_json', 'sparkx_application_json', 'story_poll_json',
  'profile_brief', 'profile_is_private', 'profile_noob_admin_ids', 'profile_row_visible', 'profile_search_candidates',
  'is_hidden_from_me', 'can_view_author', 'is_admin', 'user_public_json_by_id', 'user_list_json_by_id', 'get_my_user'];
const fingerprints = async (upTo) => {
  const db = await createTestDb({ upTo });
  const rows = (await db.query(`select p.proname as name, md5(p.prosrc) as h from pg_proc p where p.pronamespace = 'public'::regnamespace and p.proname = any($1) order by 1`, [WATCH])).rows;
  return Object.fromEntries(rows.map((r) => [r.name, r.h]));
};
const before = await fingerprints('20261114000019_~');
const after = await fingerprints('20261114000024_~');
const lines = WATCH.map((n) => `    ('${n}', ${before[n] ? `'${before[n]}'` : 'null'}, ${after[n] ? `'${after[n]}'` : 'null'})`).join(',\n');

const sql = `-- READ-ONLY catalog check for privacy gap B (docs/PRIVACY-GAP-B-PLAN.md, Stage 4; docs/PRIVACY-GAP-B-LIVE-CHECK.md explains the answers).
-- Paste this whole file into the Supabase SQL editor and press Run. It only READS the catalog (pg_proc, pg_policies, internal_config): it creates nothing and changes nothing. Generated by scripts/supabase/make-gap-b-live-check.mjs.
-- It returns FOUR result sets in ONE table (column "part"): 1 readers, 2 policies, 3 fingerprints, 4 switch and helpers. Send the whole result back (or the rows that are not "ok").

with
-- 1. every function that runs with the CALLER'S rights and mentions the table profiles (not trigger functions).
--    Expected BEFORE the five migrations: the 17 names of the plan. Expected AFTER: no row at all.
readers as (
  select p.proname as name from pg_proc p
  where p.pronamespace = 'public'::regnamespace and not p.prosecdef and p.prorettype <> 'trigger'::regtype and p.prosrc ~* '\\mprofiles\\M'
),
-- 2. the policies on profiles. Expected: profiles_select, profiles_update, profiles_admin_update. After stage 5 profiles_select asks profile_row_visible.
pol as (
  select policyname, cmd, qual from pg_policies where schemaname = 'public' and tablename = 'profiles'
),
-- 3. does every relevant function equal the repository? (md5 of the function source; computed from the migrations)
expected(name, md5_before, md5_after) as (values
${lines}
),
fp as (
  select e.name,
         (select md5(p.prosrc) from pg_proc p where p.pronamespace = 'public'::regnamespace and p.proname = e.name limit 1) as live,
         e.md5_before, e.md5_after
  from expected e
)
select 1 as part, 'caller-rights function reading profiles' as what, (select count(*) from readers)::text || ' found: ' || coalesce((select string_agg(name, ', ' order by name) from readers), 'none') as answer,
       case when (select count(*) from readers) = 0 then 'AFTER stage 2 (expected once 20261114000020 to 24 are applied)'
            when (select count(*) from readers) = 17 then 'BEFORE stage 2 (the 17 of the plan)'
            else 'STOP: neither 0 nor 17 - read the names before any next step' end as verdict
union all
select 2, 'policy on profiles', policyname || ' (' || cmd || '): ' || coalesce(qual, ''),
       case when policyname in ('profiles_select', 'profiles_update', 'profiles_admin_update') then 'ok' else 'STOP: unknown policy' end from pol
union all
select 3, 'function fingerprint ' || name,
       case when live is null then 'missing' else live end,
       case when live is null and md5_after is null then 'ok (does not exist in the repository either)'
            when live is null then 'MISSING live (migration not run?)'
            when md5_after is not null and live = md5_after and (md5_before is null or md5_before <> md5_after) then 'AFTER (equals the repository after the five migrations)'
            when md5_before is not null and live = md5_before and (md5_after is null or md5_after <> md5_before) then 'BEFORE (equals the repository before the five migrations)'
            when live = md5_after then 'ok (identical before and after)'
            else 'DIFFERENT from the repository: live was changed by hand or another migration; STOP and read it' end
from fp
union all
select 4, 'switch profiles_row_rule', coalesce((select value from public.internal_config where key = 'profiles_row_rule'), 'row missing'),
       case when (select value from public.internal_config where key = 'profiles_row_rule') = 'off' then 'ok (OFF = today''s behaviour)'
            when (select value from public.internal_config where key = 'profiles_row_rule') = 'on' then 'ON (stage 5 is active)'
            else 'row missing: stage 1 (20261114000020) not applied yet' end
union all
select 4, 'helper ' || h.n, coalesce((select (case when p.prosecdef then 'security definer' else 'INVOKER' end) || ', search_path ' || coalesce(array_to_string(p.proconfig, ','), 'NONE') from pg_proc p where p.pronamespace = 'public'::regnamespace and p.proname = h.n limit 1), 'missing'),
       case when not exists (select 1 from pg_proc p where p.pronamespace = 'public'::regnamespace and p.proname = h.n) then 'missing (stage 1/2a not applied yet)'
            when has_function_privilege('anon', (select p.oid from pg_proc p where p.pronamespace = 'public'::regnamespace and p.proname = h.n limit 1), 'execute') then 'STOP: callable by visitors'
            else 'ok (closed to visitors)' end
from (values ('profile_brief'), ('profile_is_private'), ('profile_noob_admin_ids'), ('profile_row_visible'), ('profile_search_candidates')) as h(n)
order by 1, 2;
`;
fs.writeFileSync(path.join(MIGRATIONS_DIR, '..', 'one-off', 'gap-b-live-check.sql'), sql);
console.log(`gap-b-live-check.sql written (${WATCH.length} functions fingerprinted)`);
