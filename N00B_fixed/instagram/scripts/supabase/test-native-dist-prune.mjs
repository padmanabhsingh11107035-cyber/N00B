// The Android app file was 230+ MB because the whole website was packed inside it, although the app opens the live site. prune-native-dist.mjs keeps only what it can really show.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
let passed = 0, failed = 0;
const check = (cond, label) => { if (cond) { passed++; console.log(`  ok   ${label}`); } else { failed++; console.log(`  FAIL ${label}`); } };
const read = (p) => fs.readFileSync(p, 'utf8').split(String.fromCharCode(13)).join('');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'prune-'));
const dist = path.join(tmp, 'dist');
fs.mkdirSync(path.join(dist, 'games', 'big'), { recursive: true });
fs.writeFileSync(path.join(dist, 'native-offline.html'), read('public/native-offline.html'));
fs.copyFileSync('public/noob-icon-192.png', path.join(dist, 'noob-icon-192.png'));
fs.writeFileSync(path.join(dist, 'index.html'), 'old');
fs.writeFileSync(path.join(dist, 'games', 'big', 'x.bin'), Buffer.alloc(5 * 1024 * 1024));
fs.writeFileSync(path.join(dist, 'assets.js'), 'x');
const run = spawnSync('node', ['scripts/prune-native-dist.mjs', dist], { encoding: 'utf8' });
const left = fs.readdirSync(dist).sort();
check(run.status === 0 && left.join(',') === 'index.html,native-offline.html,noob-icon-192.png', 'only index.html, the no-connection page and its one picture are left');
check(/refresh" content="0;url=https:\/\/noobsocials\.com\//.test(fs.readFileSync(path.join(dist, 'index.html'), 'utf8')), 'index.html (never shown) only forwards to the live site');
const offline = read('public/native-offline.html');
const refs = [...offline.matchAll(/(?:src|href)="([^"#]+)"/g)].map((m) => m[1]).filter((u) => !/^https?:|^mailto:/.test(u));
check(refs.every((u) => left.includes(u)), 'everything the no-connection page uses locally is kept (' + refs.join(', ') + ')');
const bad = spawnSync('node', ['scripts/prune-native-dist.mjs', path.join(tmp, 'nothing')], { encoding: 'utf8' });
check(bad.status === 1, 'a folder without the no-connection page stops the build instead of shipping a broken app');
const wf = read('../../.github/workflows/android-build.yml'), cfg = read('capacitor.config.json');
check(/node scripts\/prune-native-dist\.mjs dist/.test(wf) && wf.indexOf('prune-native-dist') < wf.indexOf('npx cap add android') && /"url": "https:\/\/noobsocials\.com"/.test(cfg) && /"errorPath": "native-offline\.html"/.test(cfg), 'the build prunes right after the website build (before the app is assembled); the app opens the live site');
fs.rmSync(tmp, { recursive: true, force: true });
console.log(`\n${passed} passed, ${failed} failed`);
process.exit(failed ? 1 : 0);
