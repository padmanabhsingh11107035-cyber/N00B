// The logged-in user id is cached in memory after its first read so that logging into a DIFFERENT account in
// another browser tab — which shares this same localStorage — can never silently hijack an already-open tab's
// identity mid-session. Only an explicit login/logout inside THIS tab changes who we act as.
let cachedUserId: string | null | undefined = undefined;

export function setSessionUserId(userId: string | null): void {
  cachedUserId = userId;
  if (userId) {
    localStorage.setItem('ig_user_id', userId);
  } else {
    localStorage.removeItem('ig_user_id');
  }
}
